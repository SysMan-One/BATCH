/*
**  Capacity constants of the facility.
*/
#define	BATCH$K_MAXJOB		512				/* Ceiling on the length of the job queue 			*/
#define	BATCH$K_NAMESZ		64				/* Length of a job name, terminator included 			*/
#define	BATCH$K_PATHSZ		512				/* Length of a file specification, terminator included 		*/
#define	BATCH$K_USERSZ		64			/* Longest user name accepted by /USER			*/
#define	BATCH$K_CPUSZ		64 /* Length of a processor list, terminator included */
#define	BATCH$K_MAXQUE		16				/* Queues a controller may be given			*/
#define	BATCH$K_QUESZ		32				/* Length of a queue name, terminator included 			*/
#define	BATCH$K_NPARM		8				/* Number of job parameters, P1 through P8 			*/
#define	BATCH$K_PARMSZ		256				/* Length of one parameter, terminator included 		*/
#define	BATCH$K_DEFJOBLIM	16				/* Default number of simultaneously executing jobs 		*/
#define	BATCH$K_DEFPRIO		100				/* Default job priority 					*/
#define	BATCH$K_MAXPRIO		255				/* Highest job priority 					*/
#define	BATCH$K_DEFQUEUE	"SYS$BATCH"			/* Default queue name 						*/

/*
**  Job states. The value zero is left unassigned: a job held in the queue always has a state of its
**  own, and an entry that has none does not exist.
*/
#define	JOB$K_PENDING		1				/* Queued, awaiting a free execution slot 			*/
#define	JOB$K_HOLDING		2				/* Withheld: /HOLD, or the /AFTER time has not arrived 		*/
#define	JOB$K_EXECUTING		3				/* Executing, the jb_pid field is valid 			*/
#define	JOB$K_ABORTING		4				/* SIGTERM sent, awaiting termination of the process 		*/
#define	JOB$K_RETAINED		5				/* Terminated, the entry is kept for inspection 		*/

/*
**  Conditions under which the queue entry is kept after the job terminates, qualifier /RETAIN.
*/
#define	RETAIN$K_ERROR		0				/* Keep only on a nonzero exit status 				*/
#define	RETAIN$K_ALWAYS		1				/* Always keep 							*/
#define	RETAIN$K_NEVER		2				/* Never keep 							*/

/*
**  Job descriptor. The structure is deliberately flat and of fixed size: it is written to the
**  journal and passed over the socket between the utility and the job controller with no
**  transformation whatever. The fields are grouped by type, which removes alignment holes.
*/
typedef struct batch_job_t {
	unsigned int	jb_entry;				/* Queue entry number, unique and increasing 			*/
	unsigned int	jb_state;				/* Job state, one of JOB$K_* 					*/
	unsigned int	jb_prio;				/* Scheduling priority, higher means sooner 			*/
	unsigned int	jb_retain;
	unsigned int	jb_restarts;				/* Number of times the job has been restarted 			*/

	int		jb_pid;					/* PID of the shell process, valid while EXECUTING 		*/
	int		jb_uid;					/* UID of the sender, taken from SO_PEERCRED 			*/
	int		jb_gid;					/* GID of the sender, taken from SO_PEERCRED 			*/
	int		jb_exit;				/* Exit status of the interpreter 				*/
	int		jb_signal;				/* Signal number if terminated by a signal 			*/
	int		jb_keeplog;				/* /KEEP indicator: keep the log after success 			*/
	int		jb_restart;				/* /RESTART indicator: run again after a restart		*/
	int		jb_logclient;				/* The log was named by the client, not built here	*/
	int		jb_logcwd;				/* The log belongs in jb_cwd, not in the spool		*/

	long long	jb_dev;					/* Device the script was on when submitted		*/
	long long	jb_ino;					/* Inode of the script when submitted			*/
	long long	jb_size;				/* Its size then					*/
	long long	jb_mtime;				/* Time it was last modified then			*/
	long long	jb_fsid;				/* Identifier of its file system then, zero if none	*/

	long long	jb_qtime;				/* Time the job was queued 					*/
	long long	jb_after;				/* Do not start before this time, zero means at once 		*/
	long long	jb_stime;				/* Time execution started, zero if it has not 			*/
	long long	jb_etime;				/* Time execution ended, zero if it has not 			*/

	char		jb_cpus [BATCH$K_CPUSZ]; /* Value of /CPU, empty when the job is not bound */
	char		jb_user [BATCH$K_USERSZ];		/* /USER: the job is to run as this user, empty means submitter	*/
	char		jb_queue [BATCH$K_QUESZ];		/* Queue name 							*/
	char		jb_name [BATCH$K_NAMESZ];		/* Job name, by default the script file name 			*/
	char		jb_script [BATCH$K_PATHSZ];		/* Absolute path of the shell script 				*/
	char		jb_logfile [BATCH$K_PATHSZ];		/* Absolute path of the job log file 				*/
	char		jb_cwd [BATCH$K_PATHSZ];		/* Working directory at submission time 			*/
	char		jb_parm [BATCH$K_NPARM][BATCH$K_PARMSZ]; /* Parameters P1 through P8 					*/
} BATCH$JOB;

/*
**  Diagnostics are issued through $PUTMSG_FAO of UTILITY$ROUTINES. Its argument is a condition value;
**  the text, an FAO control string, is taken from the table of module BATCHMSG.C, while the library
**  frames it with the body %BATCH-<severity>-<mnemonic> and prefixes the time and the position in the
**  source. The routine returns the condition value it was given, so issuing a diagnostic and returning
**  a specific condition still fit into a single expression:
**
**	return	$PUTMSG_FAO(BATCH$_NOSUCHENT, a_entry);
*/

